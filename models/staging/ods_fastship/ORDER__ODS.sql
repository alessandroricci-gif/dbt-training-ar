{{ config(materialized='table', alias='ODS_ORDERS') }}

SELECT 
    CAST(ROW_ID AS INT64) AS ROW_ID,
    TRIM(CAST(ORDER_COD AS STRING)) AS ORDER_COD,
    CAST(ORDER_DATE AS DATE) AS ORDER_DATE,
    CAST(SHIP_DATE AS DATE) AS SHIP_DATE,
    TRIM(CAST(SHIP_MODE AS STRING)) AS SHIP_MODE,
    TRIM(CAST(CLIENT_COD AS STRING)) AS CLIENT_COD,
    TRIM(CAST(CLIENT_NAME AS STRING)) AS CLIENT_NAME,
    CAST(CLIENT_ADDRESS_COD AS INT64) AS CLIENT_ADDRESS_COD,
    TRIM(CAST(CLIENT_CITY AS STRING)) AS CLIENT_CITY,
    TRIM(CAST(CLIENT_STATE AS STRING)) AS CLIENT_STATE,
    TRIM(CAST(CLIENT_COUNTRY AS STRING)) AS CLIENT_COUNTRY,
    TRIM(CAST(CLIENT_POSTAL_CODE AS STRING)) AS CLIENT_POSTAL_CODE,
    TRIM(CAST(CLIENT_SEGMENT AS STRING)) AS CLIENT_SEGMENT,
    CAST(SHIPMENT_ADDRESS_COD AS INT64) AS SHIPMENT_ADDRESS_COD,
    TRIM(CAST(SHIPMENT_CITY AS STRING)) AS SHIPMENT_CITY,
    TRIM(CAST(SHIPMENT_STATE AS STRING)) AS SHIPMENT_STATE,
    TRIM(CAST(SHIPMENT_COUNTRY AS STRING)) AS SHIPMENT_COUNTRY,
    TRIM(CAST(SHIPMENT_POSTAL_CODE AS STRING)) AS SHIPMENT_POSTAL_CODE,
    TRIM(CAST(MARKET AS STRING)) AS MARKET,
    TRIM(CAST(REGION AS STRING)) AS REGION,
    TRIM(CAST(PRODUCT_COD AS STRING)) AS PRODUCT_COD,
    TRIM(CAST(CATEGORY AS STRING)) AS CATEGORY,
    TRIM(CAST(SUB_CATEGORY AS STRING)) AS SUB_CATEGORY,
    TRIM(CAST(PRODUCT_NAME AS STRING)) AS PRODUCT_NAME,
    CAST(SALES AS FLOAT64) AS SALES,
    CAST(QUANTITY AS INT64) AS QUANTITY,
    CAST(DISCOUNT AS FLOAT64) AS DISCOUNT,
    CAST(PROFIT AS FLOAT64) AS PROFIT,
    CAST(SHIPPING_COST AS FLOAT64) AS SHIPPING_COST,
    TRIM(CAST(ORDER_PRIORITY AS STRING)) AS ORDER_PRIORITY
FROM {{ ref('order') }}